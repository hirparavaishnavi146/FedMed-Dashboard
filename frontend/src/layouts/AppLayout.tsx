// Application shell: sidebar + header + routed page content.
// Owns the sidebar state so navigation, the mobile drawer and the collapse
// button all share one source of truth.

import { useCallback, useEffect, useState } from 'react';
import { Outlet, useLocation } from 'react-router-dom';
import { Header } from '../components/Header';
import { Sidebar, findNavItem } from '../components/Sidebar';
import { IS_DEMO_MODE } from '../services/api';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import { useIsMobile } from '../hooks/useMediaQuery';

const COLLAPSE_KEY = 'fedmed.sidebar.collapsed';

export function AppLayout(): React.JSX.Element {
  const isMobile = useIsMobile();
  const location = useLocation();
  // Keeps the browser tab title in step with the page, marked [DEMO] while the
  // app renders sample data.
  useDocumentTitle(findNavItem(location.pathname)?.label);
  const [collapsed, setCollapsed] = useState<boolean>(() => {
    try {
      return window.localStorage.getItem(COLLAPSE_KEY) === 'true';
    } catch {
      return false;
    }
  });
  const [mobileOpen, setMobileOpen] = useState(false);
  const [refreshToken, setRefreshToken] = useState(0);

  useEffect(() => {
    try {
      window.localStorage.setItem(COLLAPSE_KEY, String(collapsed));
    } catch {
      /* storage can be blocked in private windows; the UI still works */
    }
  }, [collapsed]);

  // Close the drawer whenever the route changes.
  useEffect(() => {
    setMobileOpen(false);
  }, [location.pathname]);

  const toggleCollapse = useCallback(() => setCollapsed((value) => !value), []);
  const refresh = useCallback(() => setRefreshToken((value) => value + 1), []);

  return (
    <div className={`app${collapsed && !isMobile ? ' app--collapsed' : ''}`}>
      <a className="skip-link" href="#main-content">
        Skip to main content
      </a>

      <Sidebar
        collapsed={collapsed}
        onToggleCollapse={toggleCollapse}
        mobileOpen={mobileOpen}
        onCloseMobile={() => setMobileOpen(false)}
        isMobile={isMobile}
      />

      <div className="app__main">
        <Header
          onOpenMobileNav={() => setMobileOpen(true)}
          onRefresh={refresh}
          refreshing={false}
        />
        <main className="app__content" id="main-content" tabIndex={-1}>
          {/* key remounts the page on refresh so its data hook runs again */}
          <Outlet key={refreshToken} context={{ refreshToken }} />
        </main>
        <footer className="app__footer">
          <span>
            FedMed &mdash; privacy-preserving federated learning for MRI research. No model is
            trained, no federated learning runs and no real hospital is connected
            {IS_DEMO_MODE
              ? '; the values on screen come from the frontend sample file (demo mode).'
              : '; the values on screen are generated by the FedMed API.'}
          </span>
        </footer>
      </div>
    </div>
  );
}
